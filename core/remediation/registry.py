# ---------------------------------------------------------------------------
# Public registry interface
# ---------------------------------------------------------------------------


class _TemplateRegistry:
    """In-memory store. 추후 JSON / DB 로 외부화 가능 (§32.5)."""

    def __init__(
        self,
        files: list[FileTemplate],
        commands: list[CommandTemplate],
    ) -> None:
        self._files = {t.template_id: t for t in files}
        self._commands = {t.template_id: t for t in commands}

    def get_file(self, template_id: str) -> Optional[FileTemplate]:
        return self._files.get(template_id)

    def get_command(self, template_id: str) -> Optional[CommandTemplate]:
        return self._commands.get(template_id)

    def all_files(self) -> list[FileTemplate]:
        return list(self._files.values())

    def all_commands(self) -> list[CommandTemplate]:
        return list(self._commands.values())


TEMPLATE_REGISTRY = _TemplateRegistry(_FILE_TEMPLATES, _COMMAND_TEMPLATES)


def get_file_template(template_id: str) -> Optional[FileTemplate]:
    return TEMPLATE_REGISTRY.get_file(template_id)


def get_command_template(template_id: str) -> Optional[CommandTemplate]:
    return TEMPLATE_REGISTRY.get_command(template_id)
