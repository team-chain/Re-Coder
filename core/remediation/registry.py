_VAR_RE: re.Pattern[str] = re.compile(r"\{\{\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*\}\}")


def render(template_body: str, variables: dict[str, object]) -> str:
    """``{{var}}`` 단순 치환. 누락된 변수는 KeyError.

    Jinja2 보다 단순한 의도된 미니 템플릿 — 결정론적, 의미 분기 없음.
    """
    def _repl(m: re.Match[str]) -> str:
        key = m.group(1)
        if key not in variables:
            raise KeyError(f"Template variable missing: {key}")
        return str(variables[key])
    return _VAR_RE.sub(_repl, template_body)


def required_variables(template_body: str) -> list[str]:
    """템플릿이 요구하는 변수 이름 목록 (중복 제거, 등장 순서)."""
    seen: dict[str, bool] = {}
    for m in _VAR_RE.finditer(template_body):
        seen[m.group(1)] = True
    return list(seen.keys())


